/**
 * Pulls the published translations into the bundle before `next build`.
 *
 * Three outputs, all committed so a fresh clone and an offline `pnpm dev` work:
 *   messages/<locale>.json            the copy inlined into the pre-rendered HTML
 *   src/lib/ota/baseline.ts           the release hash that copy came from
 *   src/i18n/locales.generated.json   the languages that get prerendered routes
 *
 * The hash is what makes the runtime layer cheap: a visitor whose bundle already
 * matches the live release fetches the manifest and stops there.
 *
 * ⚠️ NEVER fails the build. A CDN blip, an expired DNS entry or a distribution
 * mid-publish must not stop a deploy that has nothing to do with copy — it leaves
 * the committed messages in place and the runtime layer refreshes in the browser
 * instead. Degrading to yesterday's strings is recoverable; a red deploy is not.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

// Blank-safe: an unset GitHub Actions variable arrives as "", which `??` keeps
// and `fetch` then resolves against nothing useful. See src/lib/ota/config.ts.
const MANIFEST_URL =
    process.env.NEXT_PUBLIC_OTA_MANIFEST_URL?.trim() ||
    'https://cdn.textsetu.com/REPLACE_WITH_WANDERLANE_NEXT_PUBLIC_KEY/manifest.json';

const MESSAGES_DIR = path.resolve('messages');
const BASELINE_FILE = path.resolve('src/lib/ota/baseline.ts');
const LOCALES_FILE = path.resolve('src/i18n/locales.generated.json');

/** Codes that would collide with a top-level route segment. */
const RESERVED_SEGMENTS = new Set([
    'destinations', 'stays', 'experiences', 'booking', 'about', 'contact',
    'privacy', 'terms', 'cookies', 'accessibility',
]);

/** `languageDetails` has no BCP 47 region, so og:locale is derived here. */
const OG_REGION = {
    en: 'en_US', fr: 'fr_FR', de: 'de_DE', es: 'es_ES', ja: 'ja_JP', ar: 'ar_AR',
    pt: 'pt_PT', it: 'it_IT', nl: 'nl_NL', zh: 'zh_CN', ko: 'ko_KR', hi: 'hi_IN',
};

const log = (msg) => console.log(`[sync-translations] ${msg}`);
const warn = (msg) => console.warn(`[sync-translations] ${msg}`);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/** Same guard the browser client uses — a 200 is not proof of a manifest. */
function isManifest(value) {
    return (
        typeof value === 'object' &&
        value !== null &&
        typeof value.schema === 'string' &&
        value.schema.startsWith('textsetu.distribution/') &&
        typeof value.release?.contentHash === 'string' &&
        Array.isArray(value.files) &&
        Array.isArray(value.languages)
    );
}

/**
 * Stringify so an unchanged release produces a byte-identical file.
 *
 * ⚠️ Preserves the EXISTING file's module order rather than sorting. That order
 * is curated, and re-sorting it alphabetically rewrites every line, burying the
 * two-line copy change a reviewer actually wants to see. New modules are appended
 * in manifest order; removed ones simply stop being written.
 */
function serialize(messages, previous) {
    const seen = new Set();
    const ordered = {};
    for (const key of Object.keys(previous ?? {})) {
        if (key in messages) {
            ordered[key] = messages[key];
            seen.add(key);
        }
    }
    for (const key of Object.keys(messages)) {
        if (!seen.has(key)) ordered[key] = messages[key];
    }
    return `${JSON.stringify(ordered, null, 4)}\n`;
}

function baselineSource({ contentHash, version, syncedAt, etag }) {
    return `/**
 * The release whose copy is compiled into this bundle.
 *
 * ⚠️ GENERATED by \`scripts/sync-translations.mjs\` — do not edit by hand.
 *
 * At runtime the client compares this hash against the live manifest's
 * \`release.contentHash\` and, when they match, fetches no blobs at all.
 */
export const BASELINE_CONTENT_HASH: string | null = ${JSON.stringify(contentHash)};

/** Release version the baseline came from; \`null\` when never synced. */
export const BASELINE_RELEASE_VERSION: number | null = ${version ?? 'null'};

/** When the sync ran, ISO-8601. Diagnostics only — never used for freshness. */
export const BASELINE_SYNCED_AT: string | null = ${JSON.stringify(syncedAt)};

/**
 * The \`ETag\` header value as received. Used ONLY as an \`If-None-Match\` token by
 * the build-time sync script.
 *
 * ⚠️ THIS IS NOT \`BASELINE_CONTENT_HASH\` WITH THE PREFIX STRIPPED.
 *
 *     BASELINE_MANIFEST_ETAG !== BASELINE_CONTENT_HASH.slice(7)   // always
 *
 * They hash different things. \`contentHash\` is \`sha256:<hex>\` over the RELEASE
 * CONTENT and answers "is my bundle stale". The ETag is bare hex identifying the
 * MANIFEST DOCUMENT. Any code comparing them is permanently false, and the
 * symptom looks exactly like "the cache never hits".
 */
export const BASELINE_MANIFEST_ETAG: string | null = ${JSON.stringify(etag)};
`;
}

/**
 * Fetch the manifest, tolerating a distribution that is still publishing.
 *
 * ⚠️ A `202 {"status":"building"}` IS `res.ok`. Guarding only on `!res.ok` lets
 * it through to the destructure below, where `release` is undefined and the
 * TypeError escapes `main()` as an unhandled rejection — a red build, from the
 * one script that promises never to cause one. It bites on a first publish,
 * i.e. exactly when someone is setting the repo up for the first time.
 */
async function readManifest(etag) {
    for (let attempt = 0; attempt < 5; attempt++) {
        let res;
        try {
            res = await fetch(MANIFEST_URL, {
                headers: etag ? { 'If-None-Match': etag } : {},
            });
        } catch (err) {
            warn(`could not reach the manifest (${err.message}).`);
            return { kind: 'unavailable' };
        }

        // A fresh CI runner has no HTTP cache, so the conditional request is
        // worth making here — unlike in the browser, where `fetch` surfaces a
        // cache-validated 304 as a 200 anyway.
        if (res.status === 304) return { kind: 'unchanged' };

        if (res.status === 202) {
            const retryAfter = Number(res.headers.get('Retry-After') ?? 5);
            const wait = Math.min(Number.isFinite(retryAfter) ? retryAfter : 5, 30);
            log(`release is still building — retrying in ${wait}s`);
            await sleep(wait * 1000);
            continue;
        }

        if (!res.ok) {
            warn(`manifest responded ${res.status}.`);
            return { kind: 'unavailable' };
        }

        let body;
        try {
            body = await res.json();
        } catch {
            warn('manifest was not JSON.');
            return { kind: 'unavailable' };
        }

        if (!isManifest(body)) {
            warn('response was not a manifest (an error document or a captive portal?).');
            return { kind: 'unavailable' };
        }

        return { kind: 'ok', manifest: body, etag: res.headers.get('ETag') };
    }

    warn('release was still building after 5 attempts.');
    return { kind: 'unavailable' };
}

function localesFrom(manifest) {
    const details =
        manifest.languageDetails ??
        manifest.languages.map((code) => ({ code, label: code, icon: null, direction: 'ltr' }));

    return details.map((d) => ({
        code: d.code,
        label: d.label || d.code,
        icon: d.icon ?? '',
        direction: d.direction === 'rtl' ? 'rtl' : 'ltr',
        htmlLang: d.code,
        ogLocale: OG_REGION[d.code] ?? `${d.code}_${d.code.toUpperCase()}`,
    }));
}

async function main() {
    // Offline builds, air-gapped CI and PR checks all need a way to build
    // against exactly what is committed.
    if (process.env.OTA_SKIP_SYNC === '1') {
        log('OTA_SKIP_SYNC=1 — building against the committed messages/*.json');
        return;
    }

    const baselineRaw = await readFile(BASELINE_FILE, 'utf8').catch(() => '');
    const priorEtag = baselineRaw.match(/BASELINE_MANIFEST_ETAG[^=]*=\s*"([^"]+)"/)?.[1] ?? null;

    log(`fetching ${MANIFEST_URL}`);
    const result = await readManifest(priorEtag);

    if (result.kind === 'unchanged') {
        log('manifest unchanged (304) — nothing to do');
        return;
    }
    if (result.kind === 'unavailable') {
        warn('Keeping the committed messages/*.json. The site will refresh at runtime.');
        return;
    }

    const { manifest, etag } = result;
    const { release, files, languages } = manifest;
    log(`release v${release.version}, ${files.length} files, locales: ${languages.join(', ')}`);

    const locales = localesFrom(manifest);
    const collision = locales.find((l) => RESERVED_SEGMENTS.has(l.code));
    if (collision) {
        // Not a warning. A locale code equal to a route segment silently breaks
        // `segmentOf()` and post-flatten routing, and the failure is invisible.
        console.error(
            `[sync-translations] Locale "${collision.code}" collides with a top-level ` +
                'route segment. Rename the route or drop the language.',
        );
        process.exit(1);
    }

    // Fetch everything before writing anything: a half-written locale is worse
    // than an untouched one, and the blobs are small enough to hold in memory.
    const byLocale = new Map(languages.map((code) => [code, {}]));
    try {
        await Promise.all(
            files.map(async (file) => {
                const bucket = byLocale.get(file.language);
                if (!bucket) return; // a file for a language not in `languages`
                const res = await fetch(file.url);
                if (!res.ok) throw new Error(`${file.path} responded ${res.status}`);
                const body = await res.json();
                if (file.module === null) {
                    // Not split by module: the file IS the whole locale document.
                    Object.assign(bucket, body);
                } else {
                    bucket[file.module] = body;
                }
            }),
        );
    } catch (err) {
        warn(`could not read a blob (${err.message}).`);
        warn('Keeping the committed messages/*.json. The site will refresh at runtime.');
        return;
    }

    for (const [locale, messages] of byLocale) {
        if (Object.keys(messages).length === 0) continue;
        const target = path.join(MESSAGES_DIR, `${locale}.json`);
        const current = await readFile(target, 'utf8').catch(() => null);
        const previous = current ? JSON.parse(current) : null;
        const next = serialize(messages, previous);
        if (current === next) {
            log(`${locale}.json unchanged (${Object.keys(messages).length} modules)`);
            continue;
        }
        await writeFile(target, next);
        log(`${locale}.json updated (${Object.keys(messages).length} modules)`);
    }

    await writeFile(
        LOCALES_FILE,
        `${JSON.stringify(
            {
                _generated: 'scripts/sync-translations.mjs — do not edit by hand',
                sourceLanguage: manifest.project.sourceLanguage ?? 'en',
                locales,
            },
            null,
            4,
        )}\n`,
    );
    log(`locales.generated.json: ${locales.map((l) => l.code).join(', ')}`);

    await writeFile(
        BASELINE_FILE,
        baselineSource({
            contentHash: release.contentHash,
            version: release.version,
            syncedAt: new Date().toISOString(),
            etag,
        }),
    );
    log(`baseline pinned to ${release.contentHash}`);
}

await main();
